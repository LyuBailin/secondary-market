function calcWeightedScore(scoreObj) {
  return (
    scoreObj.daily     * EVAL_WEIGHTS.daily.weight +
    scoreObj.decor     * EVAL_WEIGHTS.decor.weight +
    scoreObj.social    * EVAL_WEIGHTS.social.weight +
    scoreObj.liquidity * EVAL_WEIGHTS.liquidity.weight +
    scoreObj.preserve  * EVAL_WEIGHTS.preserve.weight
  ).toFixed(2);
}

