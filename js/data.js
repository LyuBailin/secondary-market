function calcWeightedScore(scoreObj) {
  return (
    scoreObj.spread     * EVAL_WEIGHTS.spread.weight +
    scoreObj.liquidity  * EVAL_WEIGHTS.liquidity.weight +
    scoreObj.volatility * EVAL_WEIGHTS.volatility.weight +
    scoreObj.preserve   * EVAL_WEIGHTS.preserve.weight +
    scoreObj.hot        * EVAL_WEIGHTS.hot.weight +
    scoreObj.cost       * EVAL_WEIGHTS.cost.weight
  ).toFixed(2);
}

